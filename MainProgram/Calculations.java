//this method takes array of nodes and a goal state and sorts the array according to 
//how close a node is from the array to the goal state (refference_node)
public LinkedList<Node> sortingNodesPriority(Node refferenceNode, LinkedList<Node> givenNodesList) {
    Node tempNode = new Node();


    for(int j = givenNodesList.size(); j>0;j--){
        for(int i = 1; i< j;i++){


            //If the node i-1 is less sorted than i, change their positions.
            if(sorter(givenNodesList.get(i-1).nodeState, refferenceNode.nodeState)<
            sorter(givenNodesList.get(i).nodeState, refferenceNode.nodeState)){
                tempNode =  givenNodesList.get(i-1);
                givenNodesList.set(i-1,givenNodesList.get(i));
                givenNodesList.set(i, tempNode);
            }


            //if the nodes have the same number of matching sides, check their cost.
            if(sorter(givenNodesList.get(i-1).nodeState, refferenceNode.nodeState) ==
            sorter(givenNodesList.get(i).nodeState, refferenceNode.nodeState)){
                
                if(givenNodesList.get(i).nodeCost <
                givenNodesList.get(i-1).nodeCost){
                    tempNode =  givenNodesList.get(i-1);
                    givenNodesList.set(i-1,givenNodesList.get(i));
                    givenNodesList.set(i, tempNode);
                }
            }
        }
    }

    return givenNodesList;
}


// takes 2 nodes and compares them returning a number of matching centers.
private int sorter(int[][] givenNode, int[][] referenceNode){
    int basesNumber = 0;
    for(int i = 0;i<4;i++){
        for(int j = 0; j<3;j++){
            if(givenNode[i][j*2+1] == referenceNode[i][j*2+1]){
                basesNumber++;
            }
        }
    }
return basesNumber;
}


//checks if all the centers are the same as a refference node
public boolean matchingBases(int[][] givenNode, int[][] referenceNode) {
    for(int i = 0; i<givenNode.length;i++){
        for(int j = 0; j < 3; j++){
            if(givenNode[i][j*2+1] != referenceNode[i][j*2+1]){
                return false;
            }
        }
    }
    return true;
}


/*checks how many edges are correctly placed for the bottom side, for example:
 * Side (0)     Side(1)
 * 000000       311111
 * Side (0) despite looking correct has its 3rd (0) is in the wrong spot. The correct placement would be:
 * 000000       111111
*/
public int displacedCornersAmount(int[][] givenNode, int[][] referenceNode){
    int cornersNumber = 3;
    for(int i = 0; i<3;i++){
        if(givenNode[3][i*2] == referenceNode[3][i*2]){
            if(givenNode[i][4]==referenceNode[i][4]){
                cornersNumber--;
            }
        }
    }
    return cornersNumber;
}


//this uses 2 nodes to check the 3rd side and compare how many sides are displaced with the given number
public boolean correctlyPlacedSides(int[][] givenNode, int[][] referenceNode,
                                        int currentNumberOfDisplacedSides){
    //here I take given node and check if its sides are where they need to be...
    //e.g. there are multiple blue sides, yet only one can be bordering the red.
    int counter = 3;
    for(int i = 0; i < 3; i++){
        if(givenNode[3][i*2] == referenceNode[3][i*2]){
            if(referenceNode[i][4] == givenNode[i][4]){
                counter--;
            }
        }
    }


    if(counter == currentNumberOfDisplacedSides){
        return true;
    }

    return false;
}


