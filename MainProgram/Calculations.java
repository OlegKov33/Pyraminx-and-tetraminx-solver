// this method uses node from which it is working backwards trying to make a path
//from initial state, to the "final_node"
public void ConstructPath(Node finalNode) {

    ArrayList<Node> nodesPathArray = new ArrayList<>();
    nodesPathArray.add(finalNode);

    String referenceNode = "";
    referenceNode = finalNode.nodeParent;

    for(int i = foundNodesList.size()-1;i>-1;i--){
        if(referenceNode==foundNodesList.get(i).nodeName){
            nodesPathArray.add(foundNodesList.get(i));
            referenceNode = foundNodesList.get(i).nodeParent;
        }
    }
    HowToTurn(nodesPathArray);
}

//this method uses the constructed path, to display the node
private void HowToTurn(ArrayList<Node> nodesPathArray){
    
    System.out.println(nodesPathArray.get(nodesPathArray.size()-1));
    for(int i = nodesPathArray.size()-1; i>0;i--){
        //i-1 is the eleemt we are moving towards.
        MovesInstructions(nodesPathArray.get(i-1).nodeState, nodesPathArray.get(i).nodeState);
        System.out.println(nodesPathArray.get(i-1));
    }
}


